namespace CommonUI.Controls
{
	/// <summary>
	/// Shape of a <see cref="ColorSwatch"/>.
	/// </summary>
	public enum SwatchShape
	{
		/// <summary>
		/// Square filling the control, with a border; for legends next to a text.
		/// </summary>
		Square,

		/// <summary>
		/// Circle centered in the control, without border; for small markers such as axis dots.
		/// </summary>
		Dot
	}
}
