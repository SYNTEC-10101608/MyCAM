param(
	[string]$Root = (Resolve-Path (Join-Path $PSScriptRoot "..\..\..")).Path,
	[string]$Base = "af5a2e8d"
)
# Issue-only check of the UI style unification (AUTO-23254): the files this issue added or
# changed since the master commit the branch was rebased onto (the branch started from a4b3826d before the rebase)
# follow the general and C# coding style (.editorconfig wins), and the product code keeps no check code.
# Only what the issue wrote is checked: a whole-file rule is reported when the base version of the file passed it
# (or the file is new), a line rule only for added lines.
# Designer files are generated by Visual Studio and are skipped by the line rules.
#
#   FileEncoding  encoding: UTF-8; .cs / .xml / .resx / .config / .csproj / .sln with BOM, .bat / .cmd without BOM
#   FinalNewline  the file ends with a line break
#   TrailingSpace  added line ends with spaces or tabs (.md excluded: .editorconfig keeps its trailing white space)
#   LineLength  added C# line longer than 120 columns, tab width 4 (max_line_length of .editorconfig is set for *.cs only)
#   TabIndent  added line indented with spaces instead of tabs (.cs, .ps1, .bat)
#   NoThisAccess  added C# line accesses a member with "this."
#   CommentStyle  added C# comment is a block comment or is not in English
#   OneTypePerFile  a C# file of a product project defines more than one top-level type
#   NoCheckCode  product code mentions the check programs, or a build output still contains a check program
#
# Exit code 1 on a problem.

$ErrorActionPreference = "Stop"
$problems = New-Object System.Collections.Generic.List[string]
function Report( [string]$szRule, [string]$szFile, [string]$szWhere, [string]$szText )
{
	$problems.Add( "$szRule $szFile $szWhere  $szText" )
}

$BOM_EXTENSIONS = @( ".cs", ".xml", ".resx", ".config", ".csproj", ".sln" )
$NO_BOM_EXTENSIONS = @( ".bat", ".cmd" )
$LINE_RULE_EXTENSIONS = @( ".cs", ".ps1", ".bat" )
$TEXT_EXTENSIONS = $BOM_EXTENSIONS + $NO_BOM_EXTENSIONS + @( ".ps1", ".md", ".txt" )
$PRODUCT_DIRS = "^(MyCAM|CncUI|CncManager|CommonUI|CommonData|LanguageManager|OCCTool|OCCViewer|FileTranslator)/"
$MAX_COLUMNS = 120
$strictUtf8 = New-Object System.Text.UTF8Encoding( $false, $true )

function Get-Columns( [string]$szLine )
{
	$nColumns = 0
	foreach ($ch in $szLine.ToCharArray()) {
		if ($ch -eq "`t") {
			$nColumns += 4 - ( $nColumns % 4 )
		}
		else {
			$nColumns++
		}
	}
	return $nColumns
}

# the whole-file rules a file breaks: rule -> message
function Get-FileProblems( [byte[]]$bytes, [string]$szPath )
{
	$fileProblemMap = @{}
	$szExtension = [IO.Path]::GetExtension($szPath).ToLowerInvariant()
	$hasBom = $bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF
	try {
		$szText = $strictUtf8.GetString($bytes)
	}
	catch {
		$fileProblemMap["FileEncoding"] = "not UTF-8"
		return $fileProblemMap
	}
	if ($BOM_EXTENSIONS -contains $szExtension -and -not $hasBom) {
		$fileProblemMap["FileEncoding"] = "UTF-8 with BOM expected"
	}
	if ($NO_BOM_EXTENSIONS -contains $szExtension -and $hasBom) {
		$fileProblemMap["FileEncoding"] = "UTF-8 without BOM expected"
	}
	if ($szText.Length -gt 0 -and -not $szText.EndsWith("`n")) {
		$fileProblemMap["FinalNewline"] = "no line break at the end of the file"
	}
	if ($szExtension -eq ".cs" -and $szPath -match $PRODUCT_DIRS -and $szPath -notmatch "\.Designer\.cs$") {
		$typeMatches = [regex]::Matches($szText,
			"(?m)^\t(public |internal )?(static |sealed |abstract |partial )*(class|struct|enum|interface|delegate) \w+")
		if ($typeMatches.Count -gt 1) {
			$fileProblemMap["OneTypePerFile"] = "$($typeMatches.Count) top-level types; one type per file"
		}
	}
	return $fileProblemMap
}

# the base version of a file, $null when the file is new (renamed files are compared with their old path)
$renameMap = @{}
foreach ($szStatusLine in @( & git -C $Root -c core.quotepath=off diff --name-status -M --diff-filter=R $Base )) {
	$parts = $szStatusLine -split "`t"
	$renameMap[$parts[2]] = $parts[1]
}
function Get-BaseBytes( [string]$szPath )
{
	$szBasePath = if ($renameMap.ContainsKey($szPath)) { $renameMap[$szPath] } else { $szPath }
	$szTempFile = [IO.Path]::GetTempFileName()
	try {
		& cmd /c "git -C `"$Root`" show `"$($Base):$szBasePath`" > `"$szTempFile`" 2>nul"
		if ($LASTEXITCODE -ne 0) {
			return $null
		}
		return ,[IO.File]::ReadAllBytes($szTempFile)
	}
	finally {
		Remove-Item $szTempFile -ErrorAction SilentlyContinue
	}
}

# ---------------------------------------------------------------- whole files (FileEncoding, FinalNewline, OneTypePerFile)
$changedFiles = @( & git -C $Root -c core.quotepath=off diff --name-only --diff-filter=AMR $Base | Where-Object { $_ } )
foreach ($szPath in $changedFiles) {
	$szFullPath = Join-Path $Root $szPath
	$szExtension = [IO.Path]::GetExtension($szPath).ToLowerInvariant()
	if (-not (Test-Path $szFullPath -PathType Leaf) -or $TEXT_EXTENSIONS -notcontains $szExtension) {
		continue
	}
	$fileProblemMap = Get-FileProblems ([IO.File]::ReadAllBytes($szFullPath)) $szPath
	if ($fileProblemMap.Count -eq 0) {
		continue
	}

	# a rule the base version already broke is not a problem of this issue
	$baseBytes = Get-BaseBytes $szPath
	$baseProblemMap = if ($null -ne $baseBytes) { Get-FileProblems $baseBytes $szPath } else { @{} }
	foreach ($szRule in $fileProblemMap.Keys) {
		if (-not $baseProblemMap.ContainsKey($szRule)) {
			Report $szRule $szPath "*" $fileProblemMap[$szRule]
		}
	}
}

# ---------------------------------------------------------------- added lines (TrailingSpace, LineLength, TabIndent, NoThisAccess, CommentStyle, NoCheckCode)
$szCurrentPath = $null
$nLine = 0
foreach ($szDiffLine in @( & git -C $Root -c core.quotepath=off diff -U0 --no-color $Base )) {
	if ($szDiffLine.StartsWith("+++ ")) {
		$szCurrentPath = if ($szDiffLine.StartsWith("+++ b/")) { $szDiffLine.Substring(6) } else { $null }
		continue
	}
	if ($szDiffLine -match "^@@ -\d+(,\d+)? \+(\d+)") {
		$nLine = [int]$Matches[2]
		continue
	}
	if ($null -eq $szCurrentPath -or -not $szDiffLine.StartsWith("+")) {
		continue
	}
	$szLine = $szDiffLine.Substring(1).TrimEnd("`r")
	$szWhere = "line$nLine"
	$nLine++

	$szExtension = [IO.Path]::GetExtension($szCurrentPath).ToLowerInvariant()
	$isDesigner = $szCurrentPath -match "\.Designer\.cs$"
	if ($isDesigner) {
		continue
	}
	$isLineRuleFile = $LINE_RULE_EXTENSIONS -contains $szExtension
	$isHandWrittenCs = $szExtension -eq ".cs"

	if ($TEXT_EXTENSIONS -contains $szExtension -and $szExtension -ne ".md" -and $szLine -match "[ \t]+$") {
		Report "TrailingSpace" $szCurrentPath $szWhere "trailing white space"
	}
	if ($isHandWrittenCs) {
		$nColumns = Get-Columns $szLine
		if ($nColumns -gt $MAX_COLUMNS) {
			Report "LineLength" $szCurrentPath $szWhere "$nColumns columns"
		}
	}
	if ($isLineRuleFile -and $szLine -match "^\t* +\S") {
		Report "TabIndent" $szCurrentPath $szWhere "indented with spaces"
	}
	if ($isHandWrittenCs) {
		$szCode = $szLine -replace '"(\\.|[^"\\])*"', '""'
		if ($szCode -match "\bthis\.") {
			Report "NoThisAccess" $szCurrentPath $szWhere "member accessed with this.: $($szLine.Trim())"
		}
		if ($szCode -match "/\*") {
			Report "CommentStyle" $szCurrentPath $szWhere "block comment"
		}
		if ($szCode -match "//(.*)$" -and $Matches[1] -match "[　-ヿ一-鿿＀-￯]") {
			Report "CommentStyle" $szCurrentPath $szWhere "comment not in English: $($szLine.Trim())"
		}
	}
	if ($szCurrentPath -match $PRODUCT_DIRS -and $szLine -match "UICheck|LayoutRunner|MainWindowRunner|HiddenDesktopRun") {
		Report "NoCheckCode" $szCurrentPath $szWhere "product code mentions a check program: $($szLine.Trim())"
	}
}

# check programs are compiled into the build output only while they run
foreach ($szConfig in @( "Debug", "Release" )) {
	$szOutput = Join-Path $Root "MyCAM\bin\$szConfig"
	if (-not (Test-Path $szOutput)) {
		continue
	}
	foreach ($file in Get-ChildItem $szOutput -File | Where-Object { $_.Name -match "^UICheck|Runner\.(exe|cs|pdb)$" }) {
		Report "NoCheckCode" "MyCAM/bin/$szConfig" $file.Name "check program left in the build output"
	}
}

# ---------------------------------------------------------------- result
foreach ($problem in $problems) {
	Write-Host "FAIL  $problem"
}
Write-Host "[branch rules] $($changedFiles.Count) files changed since $Base, $($problems.Count) problems"
if ($problems.Count -gt 0) {
	exit 1
}
exit 0
